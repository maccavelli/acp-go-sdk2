func mustRender(t *testing.T, f *goFile) string {
	t.Helper()
	out, err := f.render()
	if err != nil {
		t.Fatal(err)
	}
	return string(out)
}

// src joins lines into Go source text with a trailing newline.
func src(lines ...string) string { return strings.Join(lines, "\n") + "\n" }

const header = "// Code generated by acp-go-generator; DO NOT EDIT.\n\npackage acp\n"

func TestRenderLayout(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name  string
		build func(f *goFile)
		want  string
	}{
		{
			name: "doc comment and grouped const with one spec",
			build: func(f *goFile) {
				f.comment("Kinds of things.", "", "Second paragraph.")
				f.add(constDecl(true, constSpec("KindA", id("Kind"), str("a"))))
			},
			want: header + src(
				"",
				"// Kinds of things.",
				"//",
				"// Second paragraph.",
				"const (",
				"\tKindA Kind = \"a\"",
				")",
			),
		},
		{
			name: "single const without parentheses",
			build: func(f *goFile) {
				f.add(constDecl(false, constSpec("N", nil, intLit(1))))
			},
			want: header + src("", "const N = 1"),
		},
		{
			name: "empty struct, alias, and documented fields",
			build: func(f *goFile) {
				f.add(typeDecl("Empty", &ast.StructType{Fields: fields()}))
				f.line()
				f.add(aliasDecl("Raw", f.qual("encoding/json", "RawMessage")))
				f.line()
				var st fieldSet
				st.comment("The name.")
				st.add(structField("Name", id("string"), "name"))
				st.add(structField("Count", star(id("int")), "count,omitempty"))
				f.add(typeDecl("Thing", st.structType(f)))
			},
			want: header + src(
				"",
				"import \"encoding/json\"",
				"",
				"type Empty struct{}",
				"",
				"type Raw = json.RawMessage",
				"",
				"type Thing struct {",
				"\t// The name.",
				"\tName  string `json:\"name\"`",
				"\tCount *int   `json:\"count,omitempty\"`",
				"}",
			),
		},
		{
			name: "short body stays multi-line and adjacent funcs keep no blank line",
			build: func(f *goFile) {
				f.add(function("A", funcType(nil, param("", id("int"))), ret(intLit(1))))
				f.add(function("B", funcType(nil, param("", id("int"))), ret(intLit(2))))
				f.line()
				f.add(function("C", funcType(nil)))
			},
			want: header + src(
				"",
				"func A() int {",
				"\treturn 1",
				"}",
				"func B() int {",
				"\treturn 2",
				"}",
				"",
				"func C() {",
				"}",
			),
		},
		{
			name: "composite literal with several elements is one element per line",
			build: func(f *goFile) {
				f.add(function("New", funcType(nil, param("", id("T"))),
					ret(composite(id("T"), kv(id("Outer"), addr(composite(id("U"),
						kv(id("Alpha"), id("a")),
						kv(id("B"), str("b")),
					))))),
				))
			},
			want: header + src(
				"",
				"func New() T {",
				"\treturn T{Outer: &U{",
				"\t\tAlpha: a,",
				"\t\tB:     \"b\",",
				"\t}}",
				"}",
			),
		},
		{
			name: "imports are sorted and grouped",
			build: func(f *goFile) {
				f.add(function("F", funcType([]*ast.Field{param("ctx", f.qual("context", "Context"))}, param("", id("error"))),
					ret(call(f.qual("errors", "New"), str("x")))))
			},
			want: header + src(
				"",
				"import (",
				"\t\"context\"",
				"\t\"errors\"",
				")",
				"",
				"func F(ctx context.Context) error {",
				"\treturn errors.New(\"x\")",
				"}",
			),
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			f := newFile()
			tt.build(f)
			if got := mustRender(t, f); got != tt.want {
				t.Errorf("render mismatch\n--- got ---\n%s\n--- want ---\n%s", got, tt.want)
			}
		})
	}
}

func TestStructTagQuoting(t *testing.T) {
	t.Parallel()
	if got := structTag("a,omitempty").Value; got != "`json:\"a,omitempty\"`" {
		t.Errorf("structTag = %s", got)
	}
	// A backquote cannot sit in a raw string, so the tag is double-quoted.
	if got := structTag("a`b").Value; got[0] != '"' {
		t.Errorf("structTag with backquote = %s", got)
	}
}

func TestLayoutStaysBelowPrinterSentinel(t *testing.T) {
	t.Parallel()
	// go/printer treats offsets at or above 1<<30 as "no more comments".
	f := newFile()
	for range 3000 {
		f.comment("doc")
		f.add(function("F", funcType(nil), exprStmt(call(id("g")))))
		f.line()
	}
	fset := token.NewFileSet()
	file, err := f.layout(fset)
	if err != nil {
		t.Fatal(err)
	}
	if end := fset.File(file.Package).Size(); end >= 1<<30 {
		t.Fatalf("layout spans %d bytes", end)
	}
}

// TestRenderErrors requires each failure of the engine to come back as an
// error from render, not a panic.
func TestRenderErrors(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name  string
		build func(f *goFile)
		want  []string
	}{
		{"declaration go/format cannot parse back", func(f *goFile) { f.add(typeDecl("1bad", id("int"))) }, []string{"format:", "expected 'IDENT'"}},
		// With grouped imports format.Node itself re-parses what it printed,
		// so the same declaration fails in the print step.
		{"declaration format.Node cannot parse back", func(f *goFile) {
			f.add(typeDecl("A", f.qual("encoding/json", "RawMessage")))
			f.add(typeDecl("B", f.qual("errors", "Frame")))
			f.add(typeDecl("1bad", id("int")))
		}, []string{"print:", "format.Node internal error"}},
		{"doc comment with no field after it", func(f *goFile) {
			var st fieldSet
			st.add(structField("Name", id("string"), "name"))
			st.comment("Dangling doc.")
			f.add(typeDecl("Thing", st.structType(f)))
		}, []string{"has no field after it", "Dangling doc."}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			f := newFile()
			tt.build(f)
			_, err := f.render()
			if err == nil {
				t.Fatal("render succeeded")
			}
			for _, w := range tt.want {
				if !strings.Contains(err.Error(), w) {
					t.Errorf("error %q does not contain %q", err, w)
				}
			}
		})
	}
	t.Run("node go/format cannot print", func(t *testing.T) {
		t.Parallel()
		if _, err := printedSize(&ast.Field{}); err == nil || !strings.Contains(err.Error(), "print *ast.Field") {
			t.Errorf("printedSize error = %v, want one naming *ast.Field", err)
		}
	})
	t.Run("line table rejected", func(t *testing.T) {
		t.Parallel()
		l := &layout{}
		l.next()
		l.next()
		l.reserve(1, -2*lineBytes)
		if err := l.apply(token.NewFileSet()); err == nil || !strings.Contains(err.Error(), "line table rejected") {
			t.Errorf("apply error = %v, want line table rejected", err)
		}
	})
}

// TestRenderNamesTheFile requires a file that fails to render to be named in
// the error, and no file to be returned.
func TestRenderNamesTheFile(t *testing.T) {
	t.Parallel()
	ok := func(*model.Model) *goFile { f := newFile(); f.add(typeDecl("A", id("int"))); return f }
	bad := func(*model.Model) *goFile { f := newFile(); f.fail(errors.New("boom")); return f }
	files, err := renderFiles(nil, []fileBuild{{"a_gen.go", ok}, {"b_gen.go", bad}})
	if err == nil || err.Error() != "b_gen.go: boom" || files != nil {
		t.Errorf("renderFiles = %d files, %v; want none and b_gen.go: boom", len(files), err)
	}
}

// TestFirstPos requires the position of the first token for each expression
// kind firstPos knows, and nil for the others (F15).
func TestFirstPos(t *testing.T) {
	t.Parallel()
	x, lit := id("x"), str("s")
	unary := &ast.UnaryExpr{Op: token.AND, X: x}
	star := &ast.StarExpr{X: x}
	typed := &ast.CompositeLit{Type: id("T")}
	untyped := &ast.CompositeLit{}
	tests := []struct {
		name string
		expr ast.Expr
		want *token.Pos
	}{
		{"ident", x, &x.NamePos},
		{"basic literal", lit, &lit.ValuePos},
		{"key-value", &ast.KeyValueExpr{Key: x, Value: lit}, &x.NamePos},
		{"unary", unary, &unary.OpPos},
		{"star", star, &star.Star},
		{"selector", &ast.SelectorExpr{X: x, Sel: id("Y")}, &x.NamePos},
		{"call", &ast.CallExpr{Fun: x}, &x.NamePos},
		{"composite with a type", typed, &typed.Type.(*ast.Ident).NamePos},
		{"composite without a type", untyped, &untyped.Lbrace},
		{"index", &ast.IndexExpr{X: x, Index: lit}, nil},
	}
	for _, tt := range tests {
		if got := firstPos(tt.expr); got != tt.want {
			t.Errorf("%s: firstPos = %p, want %p", tt.name, got, tt.want)
		}
	}
}

// TestNestedLiteralLayout requires a composite literal whose elements are
// composite literals, or keyed composite literals, to print without blank
// lines, as gofmt writes it.
func TestNestedLiteralLayout(t *testing.T) {
	t.Parallel()
	f := newFile()
	pair := func(a, b string) ast.Expr { return composite(nil, kv(id("A"), str(a)), kv(id("B"), str(b))) }
	f.add(function("f", funcType(nil, param("", sliceOf(id("T")))), ret(composite(sliceOf(id("T")),
		pair("1", "2"),
		composite(nil, kv(id("A"), str("3")), kv(id("C"), composite(sliceOf(id("T")), pair("4", "5"), pair("6", "7")))),
	))))
	want := `func f() []T {
	return []T{
		{
			A: "1",
			B: "2",
		},
		{
			A: "3",
			C: []T{
				{
					A: "4",
					B: "5",
				},
				{
					A: "6",
					B: "7",
				},
			},
		},
	}
}
`
	if got := mustRender(t, f); !strings.HasSuffix(got, want) {
		t.Errorf("rendered:\n%s\nwant it to end with:\n%s", got, want)
	}
}
